function searchTeams(query) {
    if (!query || query.length < 2) return [];
    
    query = query.toLowerCase();
    return TEAMS_DATABASE.teams.filter(team => 
        team.name.toLowerCase().includes(query) ||
        team.nameCn.includes(query) ||
        team.league.toLowerCase().includes(query) ||
        team.leagueCn.includes(query)
    ).slice(0, 10);
}

function getTeamById(id) {
    return TEAMS_DATABASE.teams.find(team => team.id === id);
}

function getTeamsByLeague(league) {
    return TEAMS_DATABASE.teams.filter(team => team.league === league);
}

function getTeamsByRegion(region) {
    return TEAMS_DATABASE.teams.filter(team => team.region === region);
}

function getAllTeams() {
    return TEAMS_DATABASE.teams;
}

function getLeagues() {
    return TEAMS_DATABASE.leagues;
}
